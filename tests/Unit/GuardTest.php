<?php

declare(strict_types=1);

namespace Sattleme\PrestaShop\Tests\Unit;

use PHPUnit\Framework\TestCase;
use Sattleme\PrestaShop\Tools\Guard;

/**
 * The _PS_VERSION_ guard tools/Guard.php gives the embedded libraries (through PHP-Scoper) and
 * Composer's autoloader files: the file's first statement, a class keeping its comment, the code
 * still PHP.
 */
final class GuardTest extends TestCase
{
    private const GUARD = "\nif (!defined('_PS_VERSION_')) {\n    exit;\n}\n";

    public function testALibrarysFileGetsItAfterItsNamespaceAndImports(): void
    {
        $code = "<?php\n\ndeclare(strict_types=1);\n\nnamespace Vendor\\Lib;\n\nuse Vendor\\Other\\Thing;\nuse function strlen;\n\n/**\n * A class.\n */\nfinal class Example extends Thing\n{\n    use Helper;\n}\n";
        self::assertSame(
            "<?php\n\ndeclare(strict_types=1);\n\nnamespace Vendor\\Lib;\n\nuse Vendor\\Other\\Thing;\nuse function strlen;\n" . self::GUARD . "\n/**\n * A class.\n */\nfinal class Example extends Thing\n{\n    use Helper;\n}\n",
            self::parsed(Guard::add($code)),
        );
        // A licence comment before its namespace stays there.
        $licensed = "<?php\n/**\n * Licence.\n */\nnamespace Vendor\\Lib;\n\nclass Example\n{\n}\n";
        self::assertSame("<?php\n/**\n * Licence.\n */\nnamespace Vendor\\Lib;\n" . self::GUARD . "\nclass Example\n{\n}\n", self::parsed(Guard::add($licensed)));
    }

    public function testComposersFilesGetItAfterTheirFirstComment(): void
    {
        $code = "<?php\n\n// autoload.php @generated by Composer\n\nif (PHP_VERSION_ID < 50600) {\n    exit(1);\n}\n\nreturn 1;\n";
        self::assertSame("<?php\n\n// autoload.php @generated by Composer\n" . self::GUARD . "\nif (PHP_VERSION_ID < 50600) {\n    exit(1);\n}\n\nreturn 1;\n", self::parsed(Guard::add($code)));
        $static = "<?php\n\n// autoload_static.php @generated by Composer\n\nnamespace Composer\\Autoload;\n\nclass ComposerStaticInit\n{\n}\n";
        self::assertSame("<?php\n\n// autoload_static.php @generated by Composer\n\nnamespace Composer\\Autoload;\n" . self::GUARD . "\nclass ComposerStaticInit\n{\n}\n", self::parsed(Guard::add($static)));
    }

    public function testAFileWithItIsLeftAsItIs(): void
    {
        $code = "<?php\n\nnamespace Lib;\n" . self::GUARD . "\nclass Example\n{\n}\n";
        self::assertSame($code, Guard::add($code));
        self::assertSame($code, Guard::add(Guard::add("<?php\n\nnamespace Lib;\n\nclass Example\n{\n}\n")));
    }

    public function testWhatItCannotPlaceIsRefused(): void
    {
        foreach ([
            'not a PHP file' => "Text\n",
            'a namespace or declare with braces' => "<?php\n\nnamespace Lib {\n    class Example\n    {\n    }\n}\n",
            'more than one namespace' => "<?php\n\nnamespace One;\n\nclass A\n{\n}\n\nnamespace Two;\n\nclass B\n{\n}\n",
        ] as $message => $code) {
            try {
                Guard::add($code);
                self::fail($message);
            } catch (\UnexpectedValueException $e) {
                self::assertSame($message, $e->getMessage());
            }
        }
    }

    /** $code, once PHP's parser took it. */
    private static function parsed(string $code): string
    {
        \PhpToken::tokenize($code, \TOKEN_PARSE);

        return $code;
    }
}
